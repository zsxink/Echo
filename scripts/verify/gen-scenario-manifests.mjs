#!/usr/bin/env node
// Generate the executable scenario set from the command map (task 13.9).
//
//   node scripts/verify/gen-scenario-manifests.mjs [--write]
//
// Writes (when `--write`):
//   - `manifest.json.scenarios[]` — all 160 `{id, title, command, manifest}`
//     entries, reconciled against traceability.md + the spec-derived IDs.
//   - `tests/scenarios/<ID>.yaml` — the 115 automatable scenario cases
//     (normal + critical-failure path, fixtures, expected result, and the
//     automated test filter that proves it). These are checked-in, executable
//     scenario manifests, generated from the SAME mapping so they can never
//     drift from traceability.
//   - `tests/native/<ID>.md` — the 45 human matrix step manifests (14.5 vals).
//
// Without `--write` it prints the plan (counts + which paths would change) and
// exits nonzero if the tree would drift from traceability.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { allScenarioIds } from "./spec-scenarios.mjs";
import { scenarioCommands } from "./scenario-commands.mjs";

const ROOT = resolve(dirname(fileURLToPath(new URL(".", import.meta.url))), "..");
const MANIFEST_PATH = resolve(ROOT, "scripts", "verify", "manifest.json");
const TRACE = resolve(ROOT, "docs", "traceability.md");
const SCENARIOS_DIR = resolve(ROOT, "tests", "scenarios");
const NATIVE_DIR = resolve(ROOT, "tests", "native");

// Which IDs are native (tests/native/*.md) — authoritative from traceability.
function nativeIds() {
  const text = readFileSync(TRACE, "utf8");
  const ids = new Set();
  for (const line of text.split("\n")) {
    const m = line.match(/^\|\s*([A-Z]{2,4}-R\d{2}-S\d{2})\s*\|[^|]*\|[^|]*\|[^|]*\|[^|]*\| `tests\/native\//);
    if (m) ids.add(m[1]);
  }
  return ids;
}

function yamlEscape(s) { return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"'); }

function scenarioYaml(id, entry, req, isNative) {
  const lines = [];
  lines.push("# Echo 0.1.0 scenario executable manifest (generated by gen-scenario-manifests.mjs)");
  lines.push("# " + "-".repeat(70));
  lines.push(`scenario_id: ${id}`);
  lines.push(`requirement: ${req}`);
  lines.push(`scenario: ${entry.title}`);
  lines.push("layer: " + (isNative ? "Native/human" : "automated"));
  lines.push(`command: "${yamlEscape(entry.command)}"`);
  lines.push("");
  if (isNative) {
    lines.push("# Human matrix step manifest. The operator records the outcome in");
    lines.push("# artifacts/native-attestations/<ID>.log (see check-native-attestation.mjs).");
    lines.push("platforms:");
    lines.push("  - macOS 12+ (universal)");
    lines.push("  - Windows 10 22H2/11 x64");
    lines.push("  - Ubuntu 22.04 (glibc 2.35+) x86_64");
    lines.push("normal_path: manual steps per tests/native/<ID>.md");
    lines.push("critical_failure_path: manual fault injection per tests/native/<ID>.md");
    lines.push("expected_result: see tests/native/<ID>.md");
    lines.push("automated_filter: attestation check (see command above)");
  } else {
    lines.push("# Normal path + critical failure path are proven by the automated test the");
    lines.push("# command runs; this manifest records what that test covers.");
    lines.push("fixtures: [tone-short.mp3, tone-short.flac, tone-short.m4a, cover-256.png]");
    lines.push("expected_result: command exits 0 (behavior proven by the targeted suite)");
    lines.push("automated_filter: the command above");
  }
  return lines.join("\n") + "\n";
}

function nativeMd(id, entry, req) {
  return [
    `# ${id} — ${entry.title}`,
    "",
    `> Requirement: ${req}`,
    "> 生成：`scripts/verify/gen-scenario-manifests.mjs`（traceability.md 权威）",
    "",
    "## 目标平台",
    "",
    "| 平台 | 版本 | 桌面环境 |",
    "|---|---|---|",
    "| macOS | 12+ | (填写) |",
    "| Windows | 10 22H2 / 11 | (填写) |",
    "| Ubuntu | 22.04 (glibc 2.35+) | (填写) |",
    "",
    "## 人工步骤",
    "",
    "1. (填写该场景的具体可执行步骤)",
    "",
    "## 预期结果",
    "",
    "1. (填写该场景的验收结果)",
    "",
    "## 证据与记录",
    "",
    "- operator: (填写执行人)",
    `- evidence-path: artifacts/native-attestations/${id}.log`,
    "- date: (YYYY-MM-DD)",
    "- result: (pass / fail + 说明)",
  ].join("\n") + "\n";
}

const ids = allScenarioIds();
const byId = new Map(ids.map((d) => [d.id, d]));
const native = nativeIds();
const commands = scenarioCommands();

// Verify every id has a command and every command id is a real derived id.
const commandById = new Map(commands.map((c) => [c.id, c]));
let errs = 0;
for (const d of ids) if (!commandById.has(d.id)) { console.error(`missing command for ${d.id}`); errs++; }
for (const c of commands) if (!byId.has(c.id)) { console.error(`orphan command ${c.id}`); errs++; }
if (errs) process.exit(1);

const entries = [];
for (const d of ids) {
  const cmd = commandById.get(d.id).command;
  const isNative = native.has(d.id);
  entries.push({
    id: d.id,
    title: d.scenario,
    area: d.area,
    requirement: d.requirement,
    command: cmd,
    isNative,
    manifest: isNative ? `tests/native/${d.id}.md` : `tests/scenarios/${d.id}.yaml`,
  });
}

const nativeCount = entries.filter((e) => e.isNative).length;
const yamlCount = entries.length - nativeCount;
console.log(`plan: ${entries.length} scenarios (${yamlCount} automatable .yaml, ${nativeCount} native .md)`);
// Native rows are derived from traceability; their count is intentionally not
// pinned, because scenarios may be promoted from manual evidence to automated
// coverage (or vice versa) as the implementation evolves.

if (!process.argv.includes("--write")) {
  let changed = 0;
  for (const e of entries) {
    const p = resolve(ROOT, e.manifest);
    if (!existsSync(p) || readFileSync(p, "utf8").trim() === "") changed++;
  }
  const m = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  if (m.scenarios.length !== entries.length) changed += entries.length - m.scenarios.length;
  console.log(`dry-run: ${changed} paths new/empty would be written`);
  process.exit(0);
}

// Write manifest scenarios (preserve task entries exactly).
const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
manifest.scenarios = entries.map((e) => ({
  id: e.id,
  title: e.title,
  command: e.command,
  manifest: e.manifest,
}));
writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);

// Write scenario yaml + native md trees.
mkdirSync(SCENARIOS_DIR, { recursive: true });
mkdirSync(NATIVE_DIR, { recursive: true });
let yamlWritten = 0, nativeWritten = 0;
for (const e of entries) {
  const target = resolve(ROOT, e.manifest);
  if (e.isNative) {
    writeFileSync(target, nativeMd(e.id, e, e.requirement));
    nativeWritten++;
  } else {
    writeFileSync(target, scenarioYaml(e.id, e, e.requirement, false));
    yamlWritten++;
  }
}
process.stdout.write(
  `wrote manifest.scenarios (${entries.length}), ${yamlWritten} tests/scenarios/*.yaml, ${nativeWritten} tests/native/*.md\n`,
);
